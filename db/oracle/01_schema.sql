CREATE TABLE sd_users (
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  email          VARCHAR2(254 CHAR) NOT NULL,
  name           VARCHAR2(60 CHAR)  NOT NULL,
  password_hash  VARCHAR2(200)      NOT NULL,
  daily_goal     NUMBER(4)          DEFAULT 20 NOT NULL,
  created_at     TIMESTAMP          DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sd_users_pk PRIMARY KEY (id),
  CONSTRAINT sd_users_goal_ck CHECK (daily_goal BETWEEN 5 AND 500)
);
-- Índice basado en función: email único sin distinguir mayúsculas
CREATE UNIQUE INDEX sd_users_email_uk ON sd_users (LOWER(email));

-- Sesiones web y tokens de API: solo se almacena el SHA-256 del token
CREATE TABLE sd_sessions (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  token_hash  CHAR(64)           NOT NULL,
  user_id     NUMBER             NOT NULL,
  kind        VARCHAR2(10)       DEFAULT 'web' NOT NULL,
  label       VARCHAR2(60 CHAR),
  created_at  TIMESTAMP          DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  expires_at  TIMESTAMP          NOT NULL,
  CONSTRAINT sd_sessions_pk PRIMARY KEY (id),
  CONSTRAINT sd_sessions_token_uk UNIQUE (token_hash),
  CONSTRAINT sd_sessions_kind_ck CHECK (kind IN ('web', 'api')),
  CONSTRAINT sd_sessions_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_sessions_user_ix ON sd_sessions (user_id, kind);

-- Estado SM-2 por usuario y elemento (tarjeta, pregunta o drill)
CREATE TABLE sd_reviews (
  user_id        NUMBER        NOT NULL,
  item_id        VARCHAR2(40)  NOT NULL,
  chapter_id     VARCHAR2(20)  NOT NULL,
  ease           NUMBER(6, 4)  NOT NULL,
  interval_days  NUMBER(12, 6) NOT NULL,
  reps           NUMBER(6)     NOT NULL,
  lapses         NUMBER(6)     NOT NULL,
  due_at         TIMESTAMP     NOT NULL,
  last_grade     NUMBER(1)     NOT NULL,
  updated_at     TIMESTAMP     NOT NULL,
  CONSTRAINT sd_reviews_pk PRIMARY KEY (user_id, item_id),
  CONSTRAINT sd_reviews_grade_ck CHECK (last_grade BETWEEN 0 AND 3),
  CONSTRAINT sd_reviews_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_reviews_due_ix ON sd_reviews (user_id, due_at);

CREATE TABLE sd_attempts (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  user_id       NUMBER        NOT NULL,
  item_id       VARCHAR2(40)  NOT NULL,
  chapter_id    VARCHAR2(20)  NOT NULL,
  attempt_mode  VARCHAR2(10)  NOT NULL,
  correct       NUMBER(1)     NOT NULL,
  created_at    TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sd_attempts_pk PRIMARY KEY (id),
  CONSTRAINT sd_attempts_correct_ck CHECK (correct IN (0, 1)),
  CONSTRAINT sd_attempts_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_attempts_user_ix ON sd_attempts (user_id, created_at);

CREATE TABLE sd_sections_read (
  user_id     NUMBER        NOT NULL,
  chapter_id  VARCHAR2(20)  NOT NULL,
  section_id  VARCHAR2(20)  NOT NULL,
  read_at     TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sd_sections_read_pk PRIMARY KEY (user_id, chapter_id, section_id),
  CONSTRAINT sd_sections_read_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);

CREATE TABLE sd_custom_cards (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  user_id     NUMBER        NOT NULL,
  chapter_id  VARCHAR2(20)  NOT NULL,
  front       CLOB          NOT NULL,
  back        CLOB          NOT NULL,
  created_at  TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sd_custom_cards_pk PRIMARY KEY (id),
  CONSTRAINT sd_custom_cards_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_custom_cards_user_ix ON sd_custom_cards (user_id, chapter_id);

CREATE TABLE sd_exams (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  user_id      NUMBER          NOT NULL,
  item_ids     CLOB            NOT NULL,
  chapters     VARCHAR2(2000)  NOT NULL,
  time_limit   NUMBER(6)       NOT NULL,
  started_at   TIMESTAMP       NOT NULL,
  finished_at  TIMESTAMP,
  score        NUMBER(4),
  total        NUMBER(4)       NOT NULL,
  CONSTRAINT sd_exams_pk PRIMARY KEY (id),
  CONSTRAINT sd_exams_items_json_ck CHECK (item_ids IS JSON),
  CONSTRAINT sd_exams_chapters_json_ck CHECK (chapters IS JSON),
  CONSTRAINT sd_exams_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_exams_user_ix ON sd_exams (user_id, finished_at);

CREATE TABLE sd_drill_submissions (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  user_id     NUMBER        NOT NULL,
  item_id     VARCHAR2(40)  NOT NULL,
  chapter_id  VARCHAR2(20)  NOT NULL,
  code        CLOB          NOT NULL,
  passed      NUMBER(3)     NOT NULL,
  total       NUMBER(3)     NOT NULL,
  elapsed_ms  NUMBER(10)    NOT NULL,
  time_limit  NUMBER(6)     NOT NULL,
  created_at  TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sd_drill_submissions_pk PRIMARY KEY (id),
  CONSTRAINT sd_drill_submissions_user_fk FOREIGN KEY (user_id) REFERENCES sd_users (id) ON DELETE CASCADE
);
CREATE INDEX sd_drill_submissions_user_ix ON sd_drill_submissions (user_id, created_at);
